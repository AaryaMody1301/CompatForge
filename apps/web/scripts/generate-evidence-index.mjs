import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDirectory, "..");
const repositoryRoot = path.resolve(webRoot, "../..");
const outputPath = path.join(webRoot, "src/lib/evidence.generated.ts");

async function listJsonFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await listJsonFiles(entryPath)));
    } else if (entry.isFile() && entry.name.endsWith(".json")) {
      files.push(entryPath);
    }
  }

  return files.sort((left, right) => left.localeCompare(right, "en"));
}

function moduleSpecifier(filePath) {
  let relative = path.relative(path.dirname(outputPath), filePath).split(path.sep).join("/");
  if (!relative.startsWith(".")) relative = `./${relative}`;
  return relative;
}

function renderIndex(observationFiles, vendorFiles) {
  const lines = [
    "// Generated by scripts/generate-evidence-index.mjs. Do not edit by hand.",
    "// Every canonical evidence JSON file must be represented here so the public web app cannot silently omit reviewed evidence.",
  ];

  observationFiles.forEach((filePath, index) => {
    lines.push(`import observation${index} from ${JSON.stringify(moduleSpecifier(filePath))};`);
  });
  vendorFiles.forEach((filePath, index) => {
    lines.push(`import supportStatement${index} from ${JSON.stringify(moduleSpecifier(filePath))};`);
  });

  lines.push("", "export const canonicalObservationDocuments = [");
  observationFiles.forEach((_, index) => lines.push(`  observation${index},`));
  lines.push("] as const;", "", "export const canonicalSupportStatementDocuments = [");
  vendorFiles.forEach((_, index) => lines.push(`  supportStatement${index},`));
  lines.push("] as const;", "");

  return `${lines.join("\n")}\n`;
}

const observationDirectory = path.join(repositoryRoot, "data/evidence/observations");
const vendorDirectory = path.join(repositoryRoot, "data/evidence/vendor");
const expected = renderIndex(
  await listJsonFiles(observationDirectory),
  await listJsonFiles(vendorDirectory),
);

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // A missing generated file is reported as stale below.
  }

  if (current !== expected) {
    console.error(
      "Web evidence index is stale. Run `npm run generate:evidence-index` from apps/web and commit the result.",
    );
    process.exitCode = 1;
  } else {
    console.log("Web evidence index matches all canonical evidence JSON files.");
  }
} else {
  await writeFile(outputPath, expected, "utf8");
  console.log(`Wrote ${path.relative(repositoryRoot, outputPath)}.`);
}
